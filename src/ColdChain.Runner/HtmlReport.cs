using System.Globalization;
using System.Net;
using System.Text;
using ColdChain.Core.Domain;
using ColdChain.Core.Engine;

namespace ColdChain.Runner;

public sealed record ChartData(
    string TruckId,
    CargoProfile Profile,
    string? Description,
    IReadOnlyList<Reading> Readings,
    IReadOnlyList<Reading> Faults,
    IReadOnlyList<Incident> Incidents,
    IReadOnlyList<AlertEvent> Events,
    int NaiveBreaches,
    IReadOnlyList<Reading>? FileRows = null,
    IReadOnlyList<DateTimeOffset>? MissingSlots = null);

public sealed record ReportSection(string Heading, string? Subheading, string? Proves, bool? Passed, string? FailureText, ChartData Chart);

public sealed record ReportModel(string Title, string Lead, string? Note, IReadOnlyList<ReportSection> Sections, TimeSpan SilenceThreshold);

/// <summary>
/// Writes one self-contained HTML file: inline CSS and inline SVG charts, no scripts, no network.
/// It opens offline in any browser, so the reviewer needs nothing beyond the .NET SDK.
/// </summary>
public static class HtmlReport
{
    private static readonly CultureInfo Inv = CultureInfo.InvariantCulture;

    public static void Write(string path, ReportModel model)
    {
        var sb = new StringBuilder();
        sb.Append("""
<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
""");
        sb.Append($"<title>{H(model.Title)}</title>\n");
        sb.Append("<link rel=\"preconnect\" href=\"https://fonts.googleapis.com\">\n");
        sb.Append("<link rel=\"stylesheet\" href=\"https://fonts.googleapis.com/css2?family=IBM+Plex+Sans:wght@400;500;600&display=swap\">\n");
        sb.Append("<style>\n").Append(Css).Append("</style>\n</head>\n<body>\n<main>\n");

        sb.Append("<header class=\"intro\">\n");
        sb.Append($"<h1>{H(model.Title)}</h1>\n");
        sb.Append($"<p class=\"lead\">{H(model.Lead)}</p>\n");
        if (model.Note is not null) sb.Append($"<p class=\"note\">{H(model.Note)}</p>\n");
        sb.Append(Legend());
        sb.Append("</header>\n");

        foreach (var s in model.Sections) AppendSection(sb, s, model.SilenceThreshold);

        sb.Append("<footer><p>All times UTC. Thresholds come from config/cargo_profiles.json. Generated by ColdChain.Runner.</p></footer>\n");
        sb.Append("</main>\n</body>\n</html>\n");

        Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(path))!);
        File.WriteAllText(path, sb.ToString());
    }

    private static void AppendSection(StringBuilder sb, ReportSection s, TimeSpan silence)
    {
        var c = s.Chart;
        var pages = c.Events.Count(e => e.Severity == Severity.Critical);
        var status = s.Passed switch { true => "pass", false => "fail", _ => pages > 0 ? "paged" : "quiet" };

        sb.Append($"<section class=\"truck {status}\">\n<div class=\"truck-head\">\n");
        sb.Append($"<h2>{H(s.Heading)}</h2>\n");
        if (s.Passed is { } passed)
            sb.Append($"<span class=\"badge {(passed ? "ok" : "bad")}\">{(passed ? "Behaves as designed" : "Unexpected result")}</span>\n");
        sb.Append("</div>\n");
        if (s.Subheading is not null) sb.Append($"<p class=\"sub\">{H(s.Subheading)}</p>\n");
        if (s.Proves is not null) sb.Append($"<p class=\"proves\">{H(s.Proves)}</p>\n");
        if (s.FailureText is not null) sb.Append($"<p class=\"failure\">{H(s.FailureText)}</p>\n");

        sb.Append($"<p class=\"tally\">{c.Readings.Count} readings evaluated. A rule that alerts on every out-of-range reading " +
                  $"would have sent <strong>{c.NaiveBreaches}</strong> alert{(c.NaiveBreaches == 1 ? "" : "s")}; this engine paged " +
                  $"<strong>{pages}</strong> time{(pages == 1 ? "" : "s")}.</p>\n");

        sb.Append("<div class=\"chart\">").Append(Chart(c, silence)).Append("</div>\n");

        if (c.Incidents.Count > 0)
        {
            sb.Append("<div class=\"scroll\"><table class=\"incidents\">\n<thead><tr><th>Incident</th><th>Problem</th><th>Started</th>" +
                      "<th>Alerted</th><th>Back in range</th><th>Out of range</th><th>Peak</th><th>Notes</th></tr></thead>\n<tbody>\n");
            foreach (var i in c.Incidents)
            {
                var notes = new List<string>();
                if (i.IncludesDataGap) notes.Add("includes a data gap");
                if (i.ReopenCount > 0) notes.Add($"reopened {i.ReopenCount}x");
                if (i.RemindersSent > 0) notes.Add($"{i.RemindersSent} reminder{(i.RemindersSent == 1 ? "" : "s")}");
                if (i.MissedReadings.Count > 0) notes.Add($"{i.MissedReadings.Count} reading{(i.MissedReadings.Count == 1 ? "" : "s")} missing");
                if (i.PriorExcursions.Count > 0) notes.Add($"repeat of an excursion at {string.Join(", ", i.PriorExcursions.Select(p => Fmt.Time(p.Start)))}");
                if (i.Status == IncidentStatus.Open) notes.Add("still out of range when the data ends");
                if (i.Status == IncidentStatus.Recovering) notes.Add("back in range, not yet confirmed stable when the data ends");
                sb.Append("<tr>")
                  .Append($"<td>{H(i.Id)}</td>")
                  .Append($"<td>{(i.Direction == ExcursionDirection.High ? "Too warm" : "Too cold")}</td>")
                  .Append($"<td>{Fmt.Time(i.StartedAt)}</td>")
                  .Append($"<td>{Fmt.Time(i.AlertedAt)}</td>")
                  .Append($"<td>{(i.RecoveredAt is { } r ? Fmt.Time(r) : "not yet")}</td>")
                  .Append($"<td>{(i.OutOfRangeDuration is { } d ? Fmt.Span(d) : "ongoing")}</td>")
                  .Append($"<td class=\"num\">{Fmt.Temp(i.PeakC)}</td>")
                  .Append($"<td>{H(notes.Count == 0 ? "" : string.Join(", ", notes))}</td>")
                  .Append("</tr>\n");
            }
            sb.Append("</tbody></table></div>\n");
        }

        if (c.Events.Count > 0)
        {
            var open = s.Passed is not null ? " open" : "";
            sb.Append($"<details{open}><summary>What the engine decided ({c.Events.Count} event{(c.Events.Count == 1 ? "" : "s")})</summary>\n");
            sb.Append("<div class=\"scroll\"><table class=\"events\"><tbody>\n");
            foreach (var e in c.Events)
            {
                sb.Append($"<tr class=\"sev-{e.Severity.ToString().ToLowerInvariant()}\">")
                  .Append($"<td class=\"num\">{Fmt.Time(e.At)}</td>")
                  .Append($"<td class=\"ev\">{H(EventName(e.Type))}</td>")
                  .Append($"<td>{H(e.Message)}</td></tr>\n");
            }
            sb.Append("</tbody></table></div>\n</details>\n");
        }

        if (c.FileRows is { Count: > 0 }) AppendRawReadings(sb, c);
        sb.Append("</section>\n");
    }

    /// <summary>
    /// Every row from the source file for this truck, in timestamp order (the order the engine evaluates),
    /// with its position in the file and the expected readings that never arrived.
    /// </summary>
    private static void AppendRawReadings(StringBuilder sb, ChartData c)
    {
        var p = c.Profile;
        var rows = c.FileRows!.Select((r, i) => (Reading: r, FileRow: (int?)i + 1, Note: ""))
            .ToList();

        // Same rule as DataQuality: out of order = earlier than a row listed before it in the file.
        var latest = DateTimeOffset.MinValue;
        var seen = new HashSet<DateTimeOffset>();
        for (var k = 0; k < rows.Count; k++)
        {
            var r = rows[k].Reading;
            var notes = new List<string>();
            if (!seen.Add(r.Timestamp)) notes.Add("duplicate row, counted once");
            if (r.Timestamp < latest) notes.Add($"out of order in the file: listed after the {Fmt.Time(latest)} reading");
            else latest = r.Timestamp;
            rows[k] = rows[k] with { Note = string.Join("; ", notes) };
        }

        var missing = (c.MissingSlots ?? []).Select(t => (Reading: new Reading(c.TruckId, t, double.NaN), FileRow: (int?)null, Note: "expected reading never arrived"));
        var ordered = rows.Concat(missing).OrderBy(x => x.Reading.Timestamp).ThenBy(x => x.FileRow ?? 0).ToList();

        sb.Append($"<details><summary>Raw readings ({c.FileRows!.Count} row{(c.FileRows.Count == 1 ? "" : "s")} in the file" +
                  $"{(c.MissingSlots is { Count: > 0 } m ? $", {m.Count} missing" : "")})</summary>\n");
        sb.Append("<div class=\"scroll\"><table class=\"raw\">\n<thead><tr><th>Time</th><th>File row</th><th>Temperature</th>" +
                  "<th>Humidity</th><th>Status</th><th>Notes</th></tr></thead>\n<tbody>\n");
        foreach (var (r, fileRow, note) in ordered)
        {
            var isFault = fileRow is not null && (double.IsNaN(r.TemperatureC) ||
                c.Faults.Any(f => f.Timestamp == r.Timestamp && f.TemperatureC.Equals(r.TemperatureC)));
            var (cls, status) = fileRow is null ? ("st-missing", "Missing")
                : isFault ? ("st-fault", "Sensor fault, ignored")
                : r.TemperatureC > p.MaxC ? ("st-warm", "Too warm")
                : r.TemperatureC < p.MinC ? ("st-cold", "Too cold")
                : ("st-ok", "In range");
            sb.Append($"<tr class=\"{cls}\">")
              .Append($"<td class=\"num\">{Fmt.Time(r.Timestamp)}</td>")
              .Append($"<td class=\"num\">{(fileRow is { } n ? n.ToString(Inv) : "-")}</td>")
              .Append($"<td class=\"num\">{(fileRow is null ? "-" : double.IsNaN(r.TemperatureC) ? "not a number" : Fmt.Temp(r.TemperatureC))}</td>")
              .Append($"<td class=\"num\">{(r.HumidityPct is { } h ? h.ToString("0.#", Inv) + " %" : "-")}</td>")
              .Append($"<td class=\"st\">{status}</td>")
              .Append($"<td>{H(note)}</td></tr>\n");
        }
        sb.Append("</tbody></table></div>\n</details>\n");
    }

    // ------------------------------------------------------------------ chart

    private static string Chart(ChartData c, TimeSpan silence)
    {
        const double W = 960, Ht = 250, L = 52, R = 52, T = 30, B = 30;
        var pw = W - L - R;
        var ph = Ht - T - B;
        var p = c.Profile;

        var times = c.Readings.Select(r => r.Timestamp)
            .Concat(c.Faults.Select(f => f.Timestamp))
            .Concat(c.Events.Where(e => e.Type != EventType.ReadingRejected).Select(e => e.At)).ToList();
        if (times.Count == 0) return "<p class=\"sub\">No valid readings to chart.</p>";
        var t0 = times.Min();
        var t1 = times.Max();
        if (t1 <= t0) t1 = t0 + TimeSpan.FromHours(1);

        var temps = c.Readings.Select(r => r.TemperatureC).DefaultIfEmpty((p.MinC + p.MaxC) / 2).ToList();
        double dMin = temps.Min(), dMax = temps.Max();
        var lo = Math.Min(dMin, p.MinC >= dMin - 6 ? p.MinC : dMin) - 1;
        var hi = Math.Max(dMax, p.MaxC <= dMax + 6 ? p.MaxC : dMax) + 1;

        double X(DateTimeOffset t) => L + (t - t0).TotalSeconds / (t1 - t0).TotalSeconds * pw;
        double Y(double v) => T + (hi - v) / (hi - lo) * ph;
        double Clamp(double y) => Math.Clamp(y, T, T + ph);

        var sb = new StringBuilder();
        var label = $"Temperature for {c.TruckId} from {Fmt.Time(t0)} to {Fmt.Time(t1)}, safe range {Fmt.Range(p)}";
        sb.Append($"<svg viewBox=\"0 0 {N(W)} {N(Ht)}\" role=\"img\" aria-label=\"{H(label)}\" preserveAspectRatio=\"xMidYMid meet\">");
        sb.Append("<defs><pattern id=\"hatch-").Append(Id(c.TruckId)).Append("\" width=\"6\" height=\"6\" patternUnits=\"userSpaceOnUse\" patternTransform=\"rotate(45)\">")
          .Append("<line x1=\"0\" y1=\"0\" x2=\"0\" y2=\"6\" class=\"hatch\"/></pattern></defs>");

        // Safe corridor
        var bandTop = Clamp(Y(p.MaxC));
        var bandBottom = Clamp(Y(p.MinC));
        sb.Append($"<rect class=\"band\" x=\"{N(L)}\" y=\"{N(bandTop)}\" width=\"{N(pw)}\" height=\"{N(bandBottom - bandTop)}\"/>");

        // Gridlines and y labels
        var step = (hi - lo) switch { <= 6 => 1.0, <= 15 => 2.0, <= 30 => 5.0, _ => 10.0 };
        for (var tick = Math.Ceiling(lo / step) * step; tick <= hi; tick += step)
        {
            var v = Math.Abs(tick) < 1e-9 ? 0 : tick;
            sb.Append($"<line class=\"grid\" x1=\"{N(L)}\" x2=\"{N(L + pw)}\" y1=\"{N(Y(v))}\" y2=\"{N(Y(v))}\"/>");
            sb.Append($"<text class=\"axis\" x=\"{N(L - 8)}\" y=\"{N(Y(v) + 4)}\" text-anchor=\"end\">{v.ToString("0.#", Inv)}</text>");
        }

        // Threshold lines
        foreach (var (limit, name) in new[] { (p.MaxC, "max"), (p.MinC, "min") })
        {
            if (limit < lo || limit > hi) continue;
            sb.Append($"<line class=\"limit\" x1=\"{N(L)}\" x2=\"{N(L + pw)}\" y1=\"{N(Y(limit))}\" y2=\"{N(Y(limit))}\"/>");
            sb.Append($"<text class=\"limit-label\" x=\"{N(L + pw + 6)}\" y=\"{N(Y(limit) + 4)}\">{name} {limit.ToString("0.#", Inv)}°</text>");
        }

        // Incident spans
        foreach (var i in c.Incidents)
        {
            var end = i.RecoveredAt ?? i.ResolvedAt ?? t1;
            var cls = i.Direction == ExcursionDirection.High ? "span-warm" : "span-cold";
            sb.Append($"<rect class=\"{cls}\" x=\"{N(X(i.StartedAt))}\" y=\"{N(T)}\" width=\"{N(Math.Max(2, X(end) - X(i.StartedAt)))}\" height=\"{N(ph)}\">")
              .Append($"<title>{H($"{i.Id}: {Fmt.Time(i.StartedAt)} to {Fmt.Time(end)}, peak {Fmt.Temp(i.PeakC)}")}</title></rect>");
        }

        // Gaps (no valid data for longer than the silence threshold)
        var ordered = c.Readings.OrderBy(r => r.Timestamp).ToList();
        for (var k = 1; k < ordered.Count; k++)
        {
            var gap = ordered[k].Timestamp - ordered[k - 1].Timestamp;
            if (gap <= silence) continue;
            var x0 = X(ordered[k - 1].Timestamp);
            var x1 = X(ordered[k].Timestamp);
            sb.Append($"<rect fill=\"url(#hatch-{Id(c.TruckId)})\" class=\"gap\" x=\"{N(x0)}\" y=\"{N(T)}\" width=\"{N(x1 - x0)}\" height=\"{N(ph)}\">")
              .Append($"<title>{H($"No valid data {Fmt.Time(ordered[k - 1].Timestamp)} to {Fmt.Time(ordered[k].Timestamp)} ({Fmt.Span(gap)})")}</title></rect>");
        }

        // Expected readings that never arrived during an excursion
        foreach (var missed in c.Incidents.SelectMany(i => i.MissedReadings))
        {
            var x = X(missed);
            sb.Append($"<line class=\"missed\" x1=\"{N(x)}\" x2=\"{N(x)}\" y1=\"{N(T)}\" y2=\"{N(T + ph)}\">")
              .Append($"<title>{Fmt.Time(missed)}: expected reading missing, counted as out of range</title></line>");
            sb.Append($"<text class=\"missed-label\" x=\"{N(x)}\" y=\"{N(T + ph - 6)}\" text-anchor=\"middle\">no reading</text>");
        }

        // Temperature line, broken at gaps
        var path = new StringBuilder();
        for (var k = 0; k < ordered.Count; k++)
        {
            var move = k == 0 || ordered[k].Timestamp - ordered[k - 1].Timestamp > silence;
            path.Append(move ? 'M' : 'L').Append(N(X(ordered[k].Timestamp))).Append(',').Append(N(Y(ordered[k].TemperatureC))).Append(' ');
        }
        sb.Append($"<path class=\"temp\" d=\"{path.ToString().Trim()}\"/>");

        // Out-of-range points
        foreach (var r in ordered.Where(r => r.TemperatureC > p.MaxC || r.TemperatureC < p.MinC))
        {
            var cls = r.TemperatureC > p.MaxC ? "pt-warm" : "pt-cold";
            sb.Append($"<circle class=\"{cls}\" cx=\"{N(X(r.Timestamp))}\" cy=\"{N(Y(r.TemperatureC))}\" r=\"2.6\">")
              .Append($"<title>{Fmt.Time(r.Timestamp)}: {Fmt.Temp(r.TemperatureC)}</title></circle>");
        }

        // Sensor faults along the bottom edge
        foreach (var f in c.Faults)
        {
            var x = X(f.Timestamp);
            var y = T + ph - 6;
            sb.Append($"<path class=\"fault\" d=\"M{N(x - 4)},{N(y - 4)} L{N(x + 4)},{N(y + 4)} M{N(x + 4)},{N(y - 4)} L{N(x - 4)},{N(y + 4)}\">")
              .Append($"<title>{Fmt.Time(f.Timestamp)}: sensor fault value {Fmt.Temp(f.TemperatureC)} ignored</title></path>");
        }

        // Event markers in the top margin
        foreach (var e in c.Events)
        {
            if (e.Type is EventType.DuplicateDropped or EventType.ReadingRejected or EventType.ProfileMissing) continue;
            var x = X(e.At);
            var y = T - 13;
            var tip = $"<title>{H($"{Fmt.Time(e.At)} {EventName(e.Type)}: {e.Message}")}</title>";
            switch (e.Type)
            {
                case EventType.ExcursionAlert or EventType.ExcursionReopened or EventType.SensorSilentDuringExcursion:
                    sb.Append($"<line class=\"page-line\" x1=\"{N(x)}\" x2=\"{N(x)}\" y1=\"{N(T)}\" y2=\"{N(T + ph)}\"/>");
                    sb.Append($"<path class=\"m-page\" d=\"M{N(x)},{N(y + 7)} L{N(x - 6)},{N(y - 5)} L{N(x + 6)},{N(y - 5)} Z\">{tip}</path>");
                    break;
                case EventType.Reminder:
                    sb.Append($"<circle class=\"m-warn\" cx=\"{N(x)}\" cy=\"{N(y)}\" r=\"4\">{tip}</circle>");
                    break;
                case EventType.Resolved:
                    sb.Append($"<path class=\"m-ok\" d=\"M{N(x - 5)},{N(y)} L{N(x - 1.5)},{N(y + 4)} L{N(x + 5)},{N(y - 4)}\">{tip}</path>");
                    break;
                case EventType.DeviceOffline or EventType.DeviceBackOnline or EventType.SensorFault or EventType.LateReading:
                    sb.Append($"<rect class=\"m-device\" x=\"{N(x - 4)}\" y=\"{N(y - 4)}\" width=\"8\" height=\"8\">{tip}</rect>");
                    break;
                default:
                    sb.Append($"<circle class=\"m-info\" cx=\"{N(x)}\" cy=\"{N(y)}\" r=\"3.5\">{tip}</circle>");
                    break;
            }
        }

        // Time axis
        var span = t1 - t0;
        var tickStep = span.TotalHours switch { <= 2 => TimeSpan.FromMinutes(15), <= 5 => TimeSpan.FromMinutes(30), <= 12 => TimeSpan.FromHours(2), _ => TimeSpan.FromHours(3) };
        var firstTick = new DateTimeOffset(t0.UtcDateTime.Date, TimeSpan.Zero);
        while (firstTick < t0) firstTick += tickStep;
        for (var t = firstTick; t <= t1; t += tickStep)
            sb.Append($"<text class=\"axis\" x=\"{N(X(t))}\" y=\"{N(T + ph + 20)}\" text-anchor=\"middle\">{Fmt.Time(t)}</text>");
        sb.Append($"<text class=\"axis\" x=\"{N(L - 8)}\" y=\"{N(T - 18)}\" text-anchor=\"end\">°C</text>");

        sb.Append("</svg>");
        return sb.ToString();
    }

